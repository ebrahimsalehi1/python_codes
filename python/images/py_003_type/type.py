
# 🐍 use type() to find the type
# of any variable in Python 
product_id = 1
product_name = "Laptop"
price = 12.9
is_active = True

print(type(product_id))  # <class 'int'>
print(type(product_name))# <class 'str'>
print(type(price))       # <class 'float'>
print(type(is_active))   # <class 'bool'>

